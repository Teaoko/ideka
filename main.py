DARK_GRAY = (150, 150, 150)

font = pygame.font.Font(None, 36)
button_labels = ["Strength", "Endurance", "Agility", "Speed", "Meditation"]

# Left line coordinates
line_x = 0
line_top = 50
line_bottom = 450

button_width = 130
button_height = 60
num_buttons = len(button_labels)

total_space = (line_bottom - line_top) - (button_height * num_buttons)
spacing = total_space // (num_buttons + 1)

buttons = []
for i, label in enumerate(button_labels):
    button_x = line_x + 5  
    button_y = line_top + spacing*(i+1) + button_height*i
    rect = pygame.Rect(button_x, button_y, button_width, button_height)
    buttons.append((rect, label))



def draw_buttons(mouse_pos):
    for rect, label in buttons:
        color = DARK_GRAY if rect.collidepoint(mouse_pos) else GRAY
        pygame.draw.rect(screen, color, rect, border_radius=8)

        text_surface = font.render(label, True, BLACK)
        text_rect = text_surface.get_rect(center=rect.center)
        screen.blit(text_surface, text_rect)

while True:
	mouse_pos = pygame.mouse.get_pos()
	for event in pygame.event.get():
		if event.type == pygame.QUIT:
			pygame.quit()
			sys.exit()

		elif event.type == pygame.MOUSEBUTTONDOWN:
			for rect, label in buttons:
				if rect.collidepoint(event.pos):
					print(f"{label} button clicked!")

	current_time = time.time()
	progress = min((current_time - start_time) / duration, 1.0)

	value = start_value + (target_value - start_value) * progress
	current_value = int(round(value))

	if progress >= 1.0:
		start_value = value
		target_value += VPS
		start_time = current_time

	screen.fill((30, 30, 30))
	create_lines()

	text = abbreviate_number(current_value)
	text_surf = font.render(text, True, (255, 255, 255))

	screen_rect = screen.get_rect()
	text_rect = text_surf.get_rect(midtop=(screen_rect.centerx, 10))

	screen.blit(text_surf, text_rect)

	draw_buttons(mouse_pos)

	clock.tick(60)
	pygame.display.update()